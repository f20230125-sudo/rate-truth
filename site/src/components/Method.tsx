"use client";

import { useData } from "@/lib/hooks";
import { api } from "@/lib/api";
import { useSyncExternalStore } from "react";
import { Loading } from "./Loading";
import { EvalTable } from "./EvalTable";
import { Ledger } from "./Ledger";
import { CopyBlock } from "./CopyBlock";

const noopSubscribe = () => () => {};

export function Method() {
  const evaluation = useData(api.eval);
  const meta = useData(api.meta);
  const origin = useSyncExternalStore(
    noopSubscribe,
    () => window.location.origin,
    () => "<origin>",
  );
  const endpoint = `${origin}/mcp`;
  const config = JSON.stringify(
    { mcpServers: { "rate-truth": { command: "npx", args: ["-y", "mcp-remote", endpoint] } } },
    null,
    2,
  );
  return (
    <>
      <section className="report-section">
        <h2>Measure the run that happened.</h2>
        <p>These tables read the API’s eval/results.json. Missing results stay missing.</p>
        {!evaluation.data ? (
          <Loading error={evaluation.error} />
        ) : evaluation.data.run_at === null ? (
          <p className="notice">
            Evaluation not run yet. No success, grounding or latency numbers are claimed.
          </p>
        ) : (
          <>
            <p className="label">RUN AT {evaluation.data.run_at}</p>
            {Object.entries(evaluation.data)
              .filter(([key]) => key !== "run_at")
              .map(([key, value]) => (
                <EvalTable key={key} name={key} value={value} />
              ))}
          </>
        )}
      </section>
      <section className="report-section">
        <h2>What this desk can claim</h2>
        <Ledger
          facts={[
            {
              label: "Hotels & geography",
              value:
                "OpenStreetMap tags and computed distances. Untagged stars are labelled estimated; missing facts stay missing.",
            },
            {
              label: "Rates & inventory",
              value:
                "Synthetic, generated by the supplier engine. A folio is evidence of a computation, not a bookable market offer.",
            },
            {
              label: "Feeds",
              value:
                "Built to Google’s published formats. Google’s endpoints are never called. ARI without a published XSD is labelled structurally checked.",
            },
            {
              label: "Tax evidence",
              value:
                "Effective dates and confidence accompany each source. Secondary and uncertain evidence are shown in words.",
            },
            {
              label: "Agent",
              value:
                "Live when a provider is available; otherwise visibly labelled offline replay. Prices must trace to this turn’s tool results.",
            },
            { label: "Holds", value: "Mock-only, explicit confirmation required. No payment or booking." },
          ]}
        />
        <p>
          <a href="https://www.openstreetmap.org/copyright">© OpenStreetMap contributors, ODbL</a>
        </p>
        {meta.data && (
          <p className="small muted">
            OSM fetched {meta.data.osm_fetched_at} · {meta.data.hotels} hotels · {meta.data.pois} points of
            interest · tax rules {meta.data.tax_rules_version}
          </p>
        )}
        {meta.error && <Loading error={meta.error} />}
      </section>
      <section className="report-section" id="connect">
        <p className="eyebrow">CONNECT / STREAMABLE HTTP</p>
        <h2>Bring your own agent.</h2>
        <p>
          Endpoint <code>{endpoint}</code>
        </p>
        <h3>Claude Code</h3>
        <CopyBlock label="command" text={`claude mcp add --transport http rate-truth ${endpoint}`} />
        <h3>Claude Desktop</h3>
        <p className="small muted">
          Desktop configuration using the mcp-remote stdio bridge. Requires Node.js and a reachable running
          API.
        </p>
        <CopyBlock label="Desktop JSON" text={config} />
        <h3>Published tool surface</h3>
        <div className="tool-list">
          {[
            "search_hotels",
            "get_rates",
            "check_availability",
            "recommend_hotels",
            "compare_hotels",
            "hold_offer",
            "build_hotel_list_feed",
            "build_ari_messages",
            "validate_feed",
            "run_price_accuracy_audit",
            "explain_mismatch",
            "tax_rules_at",
          ].map((tool) => (
            <code key={tool}>{tool}</code>
          ))}
        </div>
        <p className="small muted">
          Resources: hotel://&#123;id&#125; · feed://latest · taxes://dubai
          <br />
          Prompts: plan-a-stay · daily-accuracy-check
        </p>
      </section>
    </>
  );
}
